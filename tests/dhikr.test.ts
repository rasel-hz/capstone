describe('approved content', () => {
  const items = Object.entries(content.items) as [string, { kind: string; text?: string; parts?: { ayat: { text: string }[] }[]; steps?: { text: string; count: number }[]; count: number | null; ref: { book: string; number: number; grade: string; url: string; text: string }; hisn?: { match: number } }][];

  it('is generated by the verification script, never edited by hand', () => {
    expect(content._about).toMatch(/Generated by scripts\/build-dhikr-content\.mjs/);
    const script = readFileSync('scripts/build-dhikr-content.mjs', 'utf8');
    for (const [key] of items) expect(script).toContain(`${key}:`);
  });

  it('has a checkable reference for every record', () => {
    for (const [, v] of items) {
      expect(['bukhari', 'muslim', 'abudawud', 'tirmidhi']).toContain(v.ref.book);
      expect(Number.isInteger(v.ref.number)).toBe(true);
      expect(v.ref.url).toBe(`https://sunnah.com/${v.ref.book}:${v.ref.number}`);
      expect(v.ref.text).toContain(String(v.ref.number));
    }
  });

  it('only uses the two Sahih collections, or a Sunan hadith al-Albani grades sahih or hasan', () => {
    for (const [, v] of items) {
      if (v.ref.book === 'bukhari' || v.ref.book === 'muslim') expect(v.ref.grade).toBe('sahih (in a Sahih collection)');
      else expect(v.ref.grade).toMatch(/^(Sahih|Hasan|Hasan Sahih|Hasan Isnaad) \(al-Albani\)$/);
      expect(v.ref.grade).not.toMatch(/daif|mawdu/i);
    }
  });

  it('keeps the source text with its own diacritics', () => {
    for (const [, v] of items) {
      const texts = v.text ? [v.text] : v.steps ? v.steps.map((s) => s.text) : v.parts!.flatMap((p) => p.ayat.map((a) => a.text));
      for (const t of texts) {
        expect(t.trim().length).toBeGreaterThan(0);
        expect(MARKS.test(t)).toBe(true);
      }
    }
  });

  it('uses counts from the hadith: a number, or free when the hadith gives none', () => {
    for (const [, v] of items) {
      if (v.count != null) expect(v.count).toBeGreaterThanOrEqual(1);
    }
    expect(content.items.tasbih_sleep.steps.map((s: { count: number }) => s.count)).toEqual([33, 33, 34]);
    expect(content.items.subhan_100.count).toBe(100);
    // Abu Dawud 5045 says three times, where the Hisn al-Muslim data said once.
    expect(content.items.qini_adhabak.count).toBe(3);
    // Muslim 2709 gives no number, so no number is claimed.
    expect(content.items.kalimat_tammat.count).toBe(1);
    for (const k of ['kalimatan', 'baqiyat', 'hawqala', 'ighfir_li']) expect(content.items[k].count).toBeNull();
  });

  it('every hadith text is also in Hisn al-Muslim', () => {
    for (const [, v] of items) if (v.kind !== 'quran') expect(v.hisn!.match).toBeGreaterThanOrEqual(0.85);
  });

  it('calms the heart with supplications for worry and distress, not random adhkar', () => {
    expect(content.challenges.dhikr_calm_heart).toEqual(['karb', 'hamm_hazan', 'makrub', 'allah_rabbi', 'dhun_nun', 'hasbuna']);
  });

  it('maps morning, evening and bedtime to their own adhkar', () => {
    expect(content.challenges.dhikr_morning).toContain('bika_asbahna');
    expect(content.challenges.dhikr_morning).not.toContain('kalimat_tammat');
    expect(content.challenges.dhikr_evening).toContain('kalimat_tammat');
    expect(content.challenges.dhikr_evening).not.toContain('bika_asbahna');
    expect(content.challenges.dhikr_sleep.at(-1)).toBe('aslamtu');
    for (const k of ['muawwidhat_sleep', 'kursi_sleep', 'bismika_amut']) expect(content.challenges.dhikr_sleep).toContain(k);
  });

  it('documents every record', () => {
    const doc = readFileSync('docs/dhikr-challenges.md', 'utf8');
    for (const [key, v] of items) {
      expect(doc).toContain(`\`${key}\``);
      expect(doc).toContain(v.ref.url);
    }
  });
});

describe('the counter', () => {
  const item = dhikrItems('dhikr_morning').find((x) => x.key === 'juwayriyah')!.item;
  const tasbih = dhikrItems('dhikr_sleep').find((x) => x.key === 'tasbih_sleep')!.item;
  const free = dhikrItems('dhikr_moment')[0].item;

  it('counts up to the number and stops there', () => {
    let c = [0];
    for (let i = 0; i < 5; i++) c = tap(c, 0, 3);
    expect(c).toEqual([3]);
    expect(itemDone(item, c)).toBe(true);
    expect(itemDone(item, [2])).toBe(false);
  });

  it('keeps counting when there is no fixed number, and one is enough', () => {
    expect(tap([7], 0, null)).toEqual([8]);
    expect(itemDone(free, [0])).toBe(false);
    expect(itemDone(free, [1])).toBe(true);
  });

  it('needs all three tasbih counts before sleep', () => {
    expect(stepsOf(tasbih).map((s) => s.target)).toEqual([33, 33, 34]);
    expect(itemDone(tasbih, [33, 33, 33])).toBe(false);
    expect(itemDone(tasbih, [33, 33, 34])).toBe(true);
  });

  it('never completes a challenge that was only opened', () => {
    const p = (done: boolean): DhikrProgress => ({ key: 'x', counts: [0], done });
    expect(canFinish([p(false), p(false)])).toBe(false);
    expect(canFinish([p(false), p(true)])).toBe(true);
  });
});

describe('when dhikr is offered', () => {
  it('fits the local time of day', () => {
    expect(dhikrFitsNow('dhikr_morning', at(8))).toBe(true);
    expect(dhikrFitsNow('dhikr_morning', at(21))).toBe(false);
    expect(dhikrFitsNow('dhikr_evening', at(18))).toBe(true);
    expect(dhikrFitsNow('dhikr_sleep', at(23))).toBe(true);
    expect(dhikrFitsNow('dhikr_sleep', at(2))).toBe(true);
    expect(dhikrFitsNow('dhikr_sleep', at(14))).toBe(false);
    expect(dhikrFitsNow('dhikr_calm_heart', at(14))).toBe(true);
    expect(dhikrNow(at(8))).toEqual(['dhikr_morning', 'dhikr_calm_heart', 'dhikr_moment']);
  });

  it('is never picked on its own, even when the user is stressed', () => {
    const s = state();
    for (const goals of [['stress'], ['worry'], ['sleep'], ['rest']] as const) {
      const ids = recommend(s, { goals: [...goals], now: at(21).getTime() }).map((r) => r.id);
      expect(ids.some((id) => id.startsWith('dhikr_'))).toBe(false);
      // The other activities are still there.
      expect(ids.length).toBeGreaterThan(0);
    }
    expect(recommend(s, { now: at(8).getTime() }).some((r) => r.id.startsWith('dhikr_'))).toBe(false);
  });

  it('is offered when asked for by name, at a fitting time', () => {
    const s = state();
    expect(recommend(s, { prefer: ['dhikr_calm_heart'], goals: ['stress'] })[0].id).toBe('dhikr_calm_heart');
    expect(recommend(s, { prefer: ['dhikr_morning'], now: at(8).getTime() })[0].id).toBe('dhikr_morning');
    expect(recommend(s, { prefer: ['dhikr_morning'], now: at(21).getTime() }).some((r) => r.id === 'dhikr_morning')).toBe(false);
  });

  it('marks every dhikr challenge as dhikr in the recommendation rules', () => {
    for (const id of DHIKR_IDS) expect(CHALLENGE_META[id].dhikr).toBe(true);
    expect(Object.entries(CHALLENGE_META).filter(([, m]) => m.dhikr).map(([id]) => id).sort()).toEqual([...DHIKR_IDS].sort());
  });
});

describe('the companion', () => {
  async function modelInput(context: Record<string, unknown>) {
    const seen: { input: { content: string }[] }[] = [];
    const f = vi.fn(async (url: string, init: { body: string }) => {
      if (String(url).endsWith('/moderations')) return Response.json({ results: [{ categories: {} }] });
      seen.push(JSON.parse(init.body));
      return Response.json({ status: 'completed', output: [{ type: 'message', content: [{ type: 'output_text', text: JSON.stringify({ reply: 'Hi', tone: 'friendly', distress: false, context: {} }) }] }] });
    }) as unknown as typeof fetch;
    const req = buildChatRequest('I feel stressed', state()) as { context: Record<string, unknown> };
    await handleChat({ ...req, context: { ...req.context, ...context } }, { apiKey: 'test-key-not-real', fetch: f });
    const text = seen[0].input[0].content;
    // The context is sent after a short label, as one JSON object.
    return JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1)) as { activities: { id: string; note?: string }[] };
  }

  it('sees every dhikr marked with whether it fits the time now, with the rule not to write religious text', async () => {
    const ctx = await modelInput({ dhikrNow: ['dhikr_morning', 'dhikr_calm_heart', 'dhikr_moment'] });
    const ids = ctx.activities.map((a) => a.id);
    const fits = Object.fromEntries(ctx.activities.filter((a) => a.id.startsWith('dhikr_')).map((a) => [a.id, (a as { fits_now?: boolean }).fits_now]));
    // Listed, so one the user names works at any time; fits_now steers an unnamed request.
    expect(fits).toEqual({ dhikr_morning: true, dhikr_evening: false, dhikr_calm_heart: true, dhikr_moment: true, dhikr_sleep: false });
    const note = ctx.activities.find((a) => a.id === 'dhikr_calm_heart')!.note!;
    expect(note).toMatch(/never quote, write or paraphrase/);
    expect(note).toMatch(/not every time the user is stressed/);
    expect(note).toMatch(/Never present it as treatment/);
    // Every other activity is still offered as before.
    for (const id of Object.keys(CHALLENGES).filter((x) => !x.startsWith('dhikr_'))) {
      if (CHALLENGES[id as keyof typeof CHALLENGES].retired) expect(ids).not.toContain(id);
      else expect(ids).toContain(id);
    }
  });

  it('ignores anything that is not a dhikr challenge in the time list', async () => {
    const ctx = await modelInput({ dhikrNow: ['dhikr_sleep', 'video', 'nonsense', 3] });
    const fitting = ctx.activities.filter((a) => (a as { fits_now?: boolean }).fits_now).map((a) => a.id);
    expect(fitting).toEqual(['dhikr_sleep']);
  });

  it('sends only which dhikr fits the time, nothing about the user', () => {
    const req = buildChatRequest('hello', state()) as { context: { dhikrNow: unknown } };
    expect(Array.isArray(req.context.dhikrNow)).toBe(true);
    for (const id of req.context.dhikrNow as string[]) expect(DHIKR_IDS).toContain(id);
  });
});

